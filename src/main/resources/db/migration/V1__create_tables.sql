-- =====================================================================
-- TaskMaster - V1: Initial schema
-- Creates all tables, constraints and indexes.
-- NOTE: Never edit this file after it has run. Add a new V2__... file instead.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. users
-- ---------------------------------------------------------------------
CREATE TABLE users (
                       id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       full_name   VARCHAR(100)  NOT NULL,
                       email       VARCHAR(150)  NOT NULL,
                       password    VARCHAR(255)  NOT NULL,          -- BCrypt hash, never plain text
                       created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
                       updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
                       CONSTRAINT uk_users_email UNIQUE (email)
);

-- ---------------------------------------------------------------------
-- 2. teams
-- ---------------------------------------------------------------------
CREATE TABLE teams (
                       id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name        VARCHAR(100)  NOT NULL,
                       description VARCHAR(500),
                       created_by  BIGINT        NOT NULL,
                       created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
                       CONSTRAINT fk_teams_created_by FOREIGN KEY (created_by) REFERENCES users (id)
);

-- ---------------------------------------------------------------------
-- 3. team_members (User <-> Team, many-to-many with role)
-- ---------------------------------------------------------------------
CREATE TABLE team_members (
                              id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              team_id     BIGINT        NOT NULL,
                              user_id     BIGINT        NOT NULL,
                              role        VARCHAR(20)   NOT NULL,
                              joined_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
                              CONSTRAINT fk_team_members_team FOREIGN KEY (team_id) REFERENCES teams (id) ON DELETE CASCADE,
                              CONSTRAINT fk_team_members_user FOREIGN KEY (user_id) REFERENCES users (id),
                              CONSTRAINT uk_team_members_team_user UNIQUE (team_id, user_id),
                              CONSTRAINT ck_team_members_role CHECK (role IN ('OWNER', 'MEMBER'))
);

CREATE INDEX idx_team_members_user ON team_members (user_id);

-- ---------------------------------------------------------------------
-- 4. team_invitations
-- ---------------------------------------------------------------------
CREATE TABLE team_invitations (
                                  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  team_id          BIGINT        NOT NULL,
                                  invited_user_id  BIGINT        NOT NULL,
                                  invited_by       BIGINT        NOT NULL,
                                  status           VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
                                  created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
                                  CONSTRAINT fk_team_invitations_team FOREIGN KEY (team_id) REFERENCES teams (id) ON DELETE CASCADE,
                                  CONSTRAINT fk_team_invitations_invited_user FOREIGN KEY (invited_user_id) REFERENCES users (id),
                                  CONSTRAINT fk_team_invitations_invited_by FOREIGN KEY (invited_by) REFERENCES users (id),
                                  CONSTRAINT ck_team_invitations_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED'))
);

CREATE INDEX idx_team_invitations_invited_user ON team_invitations (invited_user_id);

-- Only one PENDING invitation per user per team
CREATE UNIQUE INDEX uk_team_invitations_pending
    ON team_invitations (team_id, invited_user_id)
    WHERE status = 'PENDING';

-- ---------------------------------------------------------------------
-- 5. tasks
-- ---------------------------------------------------------------------
CREATE TABLE tasks (
                       id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       title        VARCHAR(200)  NOT NULL,
                       description  TEXT,
                       due_date     DATE,
                       status       VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
                       priority     VARCHAR(20)   NOT NULL DEFAULT 'MEDIUM',
                       team_id      BIGINT,                          -- NULL = personal task
                       created_by   BIGINT        NOT NULL,
                       assignee_id  BIGINT,                          -- NULL = unassigned
                       created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
                       updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
                       CONSTRAINT fk_tasks_team FOREIGN KEY (team_id) REFERENCES teams (id) ON DELETE CASCADE,
                       CONSTRAINT fk_tasks_created_by FOREIGN KEY (created_by) REFERENCES users (id),
                       CONSTRAINT fk_tasks_assignee FOREIGN KEY (assignee_id) REFERENCES users (id) ON DELETE SET NULL,
                       CONSTRAINT ck_tasks_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'COMPLETED')),
                       CONSTRAINT ck_tasks_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH'))
);

CREATE INDEX idx_tasks_assignee   ON tasks (assignee_id);
CREATE INDEX idx_tasks_team       ON tasks (team_id);
CREATE INDEX idx_tasks_created_by ON tasks (created_by);
CREATE INDEX idx_tasks_status     ON tasks (status);

-- ---------------------------------------------------------------------
-- 6. comments
-- ---------------------------------------------------------------------
CREATE TABLE comments (
                          id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          task_id     BIGINT        NOT NULL,
                          author_id   BIGINT        NOT NULL,
                          content     TEXT          NOT NULL,
                          created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
                          CONSTRAINT fk_comments_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
                          CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE INDEX idx_comments_task ON comments (task_id);

-- ---------------------------------------------------------------------
-- 7. attachments (file metadata; the file itself is stored on disk)
-- ---------------------------------------------------------------------
CREATE TABLE attachments (
                             id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             task_id       BIGINT        NOT NULL,
                             uploaded_by   BIGINT        NOT NULL,
                             file_name     VARCHAR(255)  NOT NULL,
                             content_type  VARCHAR(100),
                             file_size     BIGINT        NOT NULL,
                             storage_path  VARCHAR(500)  NOT NULL,
                             uploaded_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
                             CONSTRAINT fk_attachments_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
                             CONSTRAINT fk_attachments_uploaded_by FOREIGN KEY (uploaded_by) REFERENCES users (id)
);

CREATE INDEX idx_attachments_task ON attachments (task_id);

-- ---------------------------------------------------------------------
-- 8. revoked_tokens (JWT logout / blacklist)
-- ---------------------------------------------------------------------
CREATE TABLE revoked_tokens (
                                id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                token_id    VARCHAR(100)  NOT NULL,
                                expires_at  TIMESTAMPTZ   NOT NULL,
                                CONSTRAINT uk_revoked_tokens_token_id UNIQUE (token_id)
);

CREATE INDEX idx_revoked_tokens_expires_at ON revoked_tokens (expires_at);
